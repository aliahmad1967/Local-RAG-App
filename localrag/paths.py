"""Path helpers. Every filesystem path in LocalRAG goes through here."""

from __future__ import annotations

import sys
from pathlib import Path

_SOURCE_ROOT = Path(__file__).resolve().parents[1]
_IS_FROZEN = bool(getattr(sys, "frozen", False))
# In a PyInstaller bundle, read-only assets live in _MEIPASS while user state
# must live beside the executable so it survives app updates/restarts.
BUNDLE_DIR = Path(getattr(sys, "_MEIPASS", _SOURCE_ROOT)).resolve()
PROJECT_ROOT = BUNDLE_DIR if _IS_FROZEN else _SOURCE_ROOT
DATA_ROOT = Path(sys.executable).resolve().parent if _IS_FROZEN else _SOURCE_ROOT
IS_FROZEN = _IS_FROZEN


def ensure_utf8_console() -> None:
    """Make console output UTF-8 so Arabic filenames/messages never crash on cp1252."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            try:
                reconfigure(encoding="utf-8", errors="replace")
            except (ValueError, OSError):  # pragma: no cover - exotic streams
                pass


def resolve_path(root: Path, raw: str) -> Path:
    """Resolve an absolute path or a project-root-relative path."""
    path = Path(raw).expanduser()
    return path if path.is_absolute() else root / path


def book_dir(books_root: Path, book_id: str) -> Path:
    """Per-book cache directory. book_id is generated by us, so it is path-safe."""
    return books_root / book_id


def page_image_path(books_root: Path, book_id: str, page_no: int, ext: str = "png") -> Path:
    """Deterministic raster path: p0001.png, p0002.png, ..."""
    return book_dir(books_root, book_id) / "pages" / f"p{page_no:04d}.{ext.lstrip('.').lower()}"
